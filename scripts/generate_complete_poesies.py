import os, json, re, urllib.request

os.makedirs('data/poesies', exist_ok=True)

def clean_wiki_text(text):
    text = re.sub(r'<ref.*?>.*?</ref>', '', text)
    text = re.sub(r'<.*?>', '', text)
    text = re.sub(r'\[\[(?:[^|\]]*\|)?([^\]]+)\]\]', r'\1', text)
    return text.strip()

# 1. Fetch Burdah from Wikisource
url_b = 'https://ar.wikisource.org/w/api.php?action=parse&pageid=85226&prop=wikitext&format=json'
req_b = urllib.request.Request(url_b, headers={'User-Agent': 'Mozilla/5.0'})
with urllib.request.urlopen(req_b) as resp:
    data_b = json.loads(resp.read().decode('utf-8'))
    wikitext_b = data_b['parse']['wikitext']['*']

m_b = re.search(r'{{أبيات\|(.*?)}}', wikitext_b, re.DOTALL)
burdah_raw = [v.strip() for v in m_b.group(1).split('\n') if v.strip() and '\\\\' in v]

burdah_verses = []
for line in burdah_raw:
    parts = line.split('\\\\')
    if len(parts) == 2:
        sadr = clean_wiki_text(parts[0])
        ajuz = clean_wiki_text(parts[1])
        burdah_verses.append((sadr, ajuz))

burdah_verses.append(("يَا رَبِّ بِالمُصْطَفَى بَلِّغْ مَقَاصِدَنَا", "وَاغْفِرْ لَنَا مَا مَضَى يَا وَاسِعَ الكَرَمِ"))

