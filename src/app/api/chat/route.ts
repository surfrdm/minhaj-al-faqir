export async function POST(req: Request) {
  try {
    const { message } = await req.json();
    if (!message || typeof message !== "string") {
      return NextResponse.json({ error: "Message is required" }, { status: 400 });
    }

    const trimmed = message.trim();

    // 1. If Gemini API key is configured, call Gemini 2.5 Flash
    if (GEMINI_API_KEY) {
      try {
        const ai = new GoogleGenAI({ apiKey: GEMINI_API_KEY });
        const response = await ai.models.generateContent({
          model: "gemini-2.5-flash",
          contents: `${SYSTEM_INSTRUCTION}\n\nسؤال السالك:\n${trimmed}`,
        });

        const replyText = response.text || "";
        let cards: any[] = [];

        // Check if cards were attached
        const cardMatch = replyText.match(/\[CARDS_JSON\]([\s\S]*?)\[\/CARDS_JSON\]/);
        let cleanedReply = replyText;
        if (cardMatch) {
          try {
            cards = JSON.parse(cardMatch[1]);
            cleanedReply = replyText.replace(/\[CARDS_JSON\][\s\S]*?\[\/CARDS_JSON\]/, "").trim();
          } catch (e) {}
        }

        if (cards.length === 0) {
          // Provide contextual default cards
          cards = [
            { title: "المسار التكويني", type: "link", url: "/masar", badge: "تكوين" },
            { title: "زاد اليوم السريع", type: "link", url: "/#daily-trio", badge: "زاد اليوم" },
            { title: "دروس السبت للشيخ سيدي منير", type: "video", url: "/dourous", badge: "فيديو" },
          ];
        }

        return NextResponse.json({ reply: cleanedReply, cards });
      } catch (geminiError: any) {
        console.error("Gemini API Error, using knowledge fallback:", geminiError);
      }
    }

    // 2. Fallback knowledge base matcher
    const matched = KNOWLEDGE_RESPONSES.find((item) =>
      item.keywords.some((kw) => trimmed.includes(kw))
    );

    if (matched) {
      return NextResponse.json({
        reply: matched.reply,
        cards: matched.cards,
      });
    }

    // Generic fallback response with rich adab
    return NextResponse.json({
      reply: `مرحباً بكم أخي الكريم في رحاب «مِنْهَاجُ الفَقِير».
سؤالكم: «${trimmed}» يتصل بآداب وسلوك الطريق القادري البودشيشي المبارك.
يقول سادتنا العارفون: "طريقنا هذا مبني على الكتاب والسنة والأدب مع المشايخ والإخوان".
يسعدني إرشادكم إلى مطالعة زاد اليوم، أو مراجعة المرحلة المخصصة في المسار التكويني، أو مشاهدة دروس السبت لفضيلة الشيخ الدكتور سيدي منير القادري بودشيش.`,
      cards: [
        { title: "المسار التكويني (المراحل الست)", type: "link", url: "/masar", badge: "مساري" },
        { title: "فضاء الفقير وتقويم الأوراد", type: "link", url: "/faqir", badge: "أوراد" },
        { title: "أدلة أصول الطريقة", type: "link", url: "/#evidence", badge: "تأصيل" },
        { title: "محاضرات ودروس السبت المشهودة", type: "video", url: "/dourous", badge: "50 درساً" },
      ],
    });
  } catch (err: any) {
    return NextResponse.json({ error: err.message }, { status: 500 });
  }
}
