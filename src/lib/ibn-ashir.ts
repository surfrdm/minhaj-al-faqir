export function getIbnAshirLessonOfTheDay(date: Date = new Date()): IbnAshirVerseLesson {
  const startOfYear = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  const index = Math.abs(dayOfYear) % IBN_ASHIR_LESSONS.length;
  return IBN_ASHIR_LESSONS[index] || IBN_ASHIR_LESSONS[0];
}
